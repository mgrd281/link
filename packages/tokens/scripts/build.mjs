function swiftNumber(v) {
  const n = Number(v);
  return Number.isInteger(n) ? `${n}` : `${n}`;
}

StyleDictionary.registerFormat({
  name: "linkyo/swift",
  format: ({ dictionary }) => {
    const group = (title, prefix, map = (t) => swiftNumber(px(t.$value)), type = "CGFloat") =>
      `    public enum ${title} {\n${byPath(dictionary, prefix)
        .map((t) => {
          const raw = t.path.slice(prefix.length).join("_");
          const name = /^\d/.test(raw) ? `s${raw}` : camel(raw);
          const doc = t.$description ? `        /// ${t.$description}\n` : "";
          return `${doc}        public static let ${name}: ${type} = ${map(t)}`;
        })
        .join("\n")}\n    }`;

    const textStyles = byPath(dictionary, ["text"])
      .map((t) => {
        const v = t.$value;
        return `        public static let ${camel(t.path[1])} = TextStyle(size: ${px(v.fontSize)}, lineHeight: ${v.lineHeight}, weight: ${v.fontWeight}, tracking: ${Number.parseFloat(v.letterSpacing)})`;
      })
      .join("\n");

    const colorNames = [...byPath(dictionary, ["color"]), ...byPath(dictionary, ["semantic"])]
      .map((t) => {
        const asset = t.path[0] === "semantic" ? pascal(t.path.slice(1).join("-")) : pascal(t.path.slice(1).join("-"));
        const name = camel(t.path.slice(1).join("-"));
        const prefix = t.path[0] === "semantic" ? "" : "palette";
        const id = prefix ? `${prefix}${pascal(name)}` : name;
        const folder = t.path[0] === "semantic" ? "Semantic" : "Palette";
        return `        public static let ${id} = Color("${folder}/${asset}", bundle: .module)`;
      })
      .join("\n");

    return `// ${HEADER}
// swiftlint:disable all

import Foundation
#if canImport(CoreGraphics)
import CoreGraphics
#endif
#if canImport(SwiftUI)
import SwiftUI
#endif

/// Linkyo design tokens. Values mirror the web tokens 1:1 (pt == CSS px).
public enum LinkyoTokens {
${group("Spacing", ["spacing"])}

${group("Size", ["size"])}

${group("Radius", ["radius"])}

${group("BorderWidth", ["border-width"])}

${group("Layout", ["layout"])}

    public enum Icon {
        public static let stroke: CGFloat = ${dictionary.tokens.icon.stroke.$value}
    }

    public struct TextStyle: Sendable, Equatable {
        public let size: CGFloat
        public let lineHeight: CGFloat
        public let weight: Int
        /// Tracking in em (multiply by size for points).
        public let tracking: CGFloat
    }

    public enum Typography {
${textStyles}
    }

    public enum Motion {
${byPath(dictionary, ["motion", "duration"])
  .map((t) => `        public static let ${t.path[2]}: Double = ${ms(t.$value) / 1000}`)
  .join("\n")}
        public static let springResponse: Double = ${dictionary.tokens.motion.spring.response.$value}
        public static let springDamping: Double = ${dictionary.tokens.motion.spring.damping.$value}
        public static let pressedScale: CGFloat = ${dictionary.tokens.motion.scale.pressed.$value}
        public static let liftScale: CGFloat = ${dictionary.tokens.motion.scale.lift.$value}
    }

    public enum Opacity {
${byPath(dictionary, ["opacity"])
  .map((t) => `        public static let ${t.path[1]}: Double = ${t.$value}`)
  .join("\n")}
    }
}

#if canImport(SwiftUI)
public extension Color {
    /// Colors from the generated asset catalog (light, dark and Increase Contrast variants).
    enum Linkyo {
${colorNames}
    }
}
#endif
`;
  },
});

/** Writes Colors.xcassets with light/dark/high-contrast appearances. */
StyleDictionary.registerAction({
  name: "linkyo/xcassets",
  do: (dictionary) => {
    const catalog = path.join(IOS_GENERATED, "Colors.xcassets");
    rmSync(catalog, { recursive: true, force: true });
    const info = { author: "xcode", version: 1 };
    const write = (file, data) => {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
    };
    write(path.join(catalog, "Contents.json"), { info });

    const component = (hex) => {
      const { r, g, b, a } = hexToRgba(hex);
      const f = (v) => (v / 255).toFixed(3);
      return { "color-space": "srgb", components: { alpha: a.toFixed(3), blue: f(b), green: f(g), red: f(r) } };
    };
    const entry = (hex, appearances) => ({
      ...(appearances ? { appearances } : {}),
      color: component(hex),
      idiom: "universal",
    });
    const DARK = { appearance: "luminosity", value: "dark" };
    const HIGH = { appearance: "contrast", value: "high" };

    for (const folder of ["Palette", "Semantic"]) {
      write(path.join(catalog, folder, "Contents.json"), { info, properties: { "provides-namespace": true } });
    }
    for (const t of byPath(dictionary, ["color"])) {
      write(path.join(catalog, "Palette", `${pascal(t.path.slice(1).join("-"))}.colorset`, "Contents.json"), {
        colors: [entry(t.$value)],
        info,
      });
    }
    for (const t of byPath(dictionary, ["semantic"])) {
      const e = ext(t);
      const dark = resolve(e.dark ?? t.$value, dictionary);
      const colors = [entry(t.$value), entry(dark, [DARK])];
      if (e.highContrast) colors.push(entry(resolve(e.highContrast, dictionary), [HIGH]));
      if (e.highContrastDark) colors.push(entry(resolve(e.highContrastDark, dictionary), [DARK, HIGH]));
      write(path.join(catalog, "Semantic", `${pascal(t.path.slice(1).join("-"))}.colorset`, "Contents.json"), {
        colors,
        info,
      });
    }
  },
  undo: () => rmSync(path.join(IOS_GENERATED, "Colors.xcassets"), { recursive: true, force: true }),
});

