/** @param {import("style-dictionary/types").TransformedToken} token */
const ext = (token) => token.$extensions?.[EXT] ?? token.original?.$extensions?.[EXT] ?? {};
/** @param {string[]} p */
const kebab = (p) => p.join("-").replace(/_/g, "-").replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
const camel = (/** @type {string} */ s) => s.replace(/[-_](\w)/g, (_, c) => c.toUpperCase());
const pascal = (/** @type {string} */ s) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
const px = (/** @type {string} */ v) => Number.parseFloat(String(v));
const rem = (/** @type {string} */ v) => `${+(px(v) / ROOT_FONT_SIZE).toFixed(4)}rem`;
const ms = (/** @type {string} */ v) => Number.parseFloat(String(v));

/** Resolve a value (possibly a reference or object of references) against the dictionary. */
function resolve(value, dictionary) {
  if (typeof value === "string") return resolveReferences(value, dictionary.unfilteredTokens ?? dictionary.tokens);
  if (Array.isArray(value)) return value.map((v) => resolve(v, dictionary));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, dictionary)]));
  }
  return value;
}

/** @param {string} hex */
function hexToRgba(hex) {
  const h = hex.replace("#", "");
  const n = (i) => Number.parseInt(h.slice(i, i + 2), 16);
  const a = h.length === 8 ? n(6) / 255 : 1;
  return { r: n(0), g: n(2), b: n(4), a };
}

/** CSS color: hex for opaque, hex8 kept (supported everywhere we ship). */
const cssColor = (/** @type {string} */ hex) => hex.toLowerCase();

/** @param {{ color: string, offsetX: string, offsetY: string, blur: string, spread: string }} s */

/**
 * CSS font stack. Families with a self-hosted face get `var(--font-face-<id>, "Family")` so apps can
 * plug in their loader (next/font) while plain CSS still works with an @font-face of that name.
 * @param {string[]} families
 * @param {string | Record<string, string> | undefined} faces  face id for the first family, or family → face id
 */
const fontStack = (families, faces) => {
  const map = typeof faces === "string" ? { [families[0]]: faces } : (faces ?? {});
  return families
    .map((family) => {
      const quoted = /[\s\d]/.test(family) && !family.startsWith("-") && !family.startsWith("ui-") ? `"${family}"` : family;
      return map[family] ? `var(--font-face-${map[family]}, ${quoted})` : quoted;
    })
    .join(", ");
};

const byPath = (dictionary, prefix) =>
  dictionary.allTokens.filter((t) => prefix.every((segment, i) => t.path[i] === segment));

