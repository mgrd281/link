// shared model: one place that decides names/values for every web output

function webModel(dictionary) {
  /** @type {[string, string][]} */ const light = [];
  /** @type {[string, string][]} */ const dark = [];
  /** @type {[string, string][]} */ const contrast = [];
  /** @type {[string, string][]} */ const contrastDark = [];

  for (const t of byPath(dictionary, ["color"])) light.push([`--color-${kebab(t.path.slice(1))}`, cssColor(t.$value)]);
  for (const t of byPath(dictionary, ["semantic"])) {
    const name = `--color-${t.path.slice(1).join("-")}`;
    const e = ext(t);
    light.push([name, cssColor(t.$value)]);
    if (e.dark) dark.push([name, cssColor(resolve(e.dark, dictionary))]);
    if (e.highContrast) contrast.push([name, cssColor(resolve(e.highContrast, dictionary))]);
    if (e.highContrastDark) contrastDark.push([name, cssColor(resolve(e.highContrastDark, dictionary))]);
  }

  for (const t of byPath(dictionary, ["font", "family"])) {
    light.push([`--font-${t.path[2]}`, fontStack(t.$value, ext(t).faces)]);
  }
  for (const t of byPath(dictionary, ["font", "weight"])) light.push([`--font-weight-${t.path[2]}`, String(t.$value)]);

  for (const t of byPath(dictionary, ["text"])) {
    const v = t.$value;
    const key = `--text-${t.path[1]}`;
    light.push([key, rem(v.fontSize)]);
    light.push([`${key}--line-height`, String(v.lineHeight)]);
    light.push([`${key}--font-weight`, String(v.fontWeight)]);
    light.push([`${key}--letter-spacing`, v.letterSpacing]);
  }
  for (const t of byPath(dictionary, ["tracking"])) light.push([`--tracking-${t.path[1]}`, t.$value]);
  for (const t of byPath(dictionary, ["leading"])) light.push([`--leading-${t.path[1]}`, String(t.$value)]);

  for (const t of byPath(dictionary, ["spacing"])) {
    light.push([`--spacing-${t.path[1]}`, px(t.$value) === 0 ? "0" : rem(t.$value)]);
  }
  for (const t of byPath(dictionary, ["size"])) light.push([`--spacing-${t.path[1]}`, rem(t.$value)]);
  for (const t of byPath(dictionary, ["layout"])) light.push([`--container-${t.path[1]}`, rem(t.$value)]);

  for (const t of byPath(dictionary, ["radius"])) light.push([`--radius-${t.path[1]}`, t.$value === "0px" ? "0" : t.$value]);
  for (const t of byPath(dictionary, ["border-width"])) light.push([`--border-width-${t.path[1]}`, t.$value]);

  for (const t of byPath(dictionary, ["motion", "duration"])) light.push([`--duration-${t.path[2]}`, `${ms(t.$value)}ms`]);
  for (const t of byPath(dictionary, ["motion", "easing"])) light.push([`--ease-${t.path[2]}`, `cubic-bezier(${t.$value.join(", ")})`]);
  for (const t of byPath(dictionary, ["motion", "scale"])) light.push([`--scale-${t.path[2]}`, String(t.$value)]);
  for (const t of byPath(dictionary, ["opacity"])) light.push([`--opacity-${t.path[1]}`, String(t.$value)]);
  for (const t of byPath(dictionary, ["blur"])) light.push([`--blur-${t.path[1]}`, t.$value]);
  for (const t of byPath(dictionary, ["z"])) light.push([`--z-${t.path[1]}`, String(t.$value)]);
  for (const t of byPath(dictionary, ["breakpoint"])) light.push([`--breakpoint-${t.path[1]}`, rem(t.$value)]);
  for (const t of byPath(dictionary, ["aspect"])) light.push([`--aspect-${t.path[1]}`, t.$value]);
  light.push(["--icon-stroke", String(dictionary.tokens.icon.stroke.$value)]);

  // Creator page roles: values are injected per page by the theme engine (src/creator).
  const creatorColors = ["bg", "surface", "surface-2", "fg", "fg-muted", "accent", "accent-fg", "accent-text", "line", "line-strong", "glass"];
  const creator = [
    ...creatorColors.map((role) => [`--color-creator-${role}`, `var(--creator-${role})`]),
    ["--font-creator-display", "var(--creator-font-display)"],
    ["--font-creator-body", "var(--creator-font-body)"],
    ["--radius-creator-button", "var(--creator-radius-button)"],
    ["--radius-creator-card", "var(--creator-radius-card)"],
    ["--spacing-creator-button", rem(resolve(dictionary.tokens.creator.button.height.$value, dictionary))],
  ];

  const darkNames = new Set(dark.map(([name]) => name));
  const lightSemantic = light.filter(([name]) => darkNames.has(name));
  return { light, dark, contrast, contrastDark, creator, lightSemantic };
}

const decls = (/** @type {[string, string][]} */ list, indent = "  ") => list.map(([k, v]) => `${indent}${k}: ${v};`).join("\n");

