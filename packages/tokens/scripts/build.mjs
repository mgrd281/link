StyleDictionary.registerFormat({
  name: "linkyo/typescript",
  format: ({ dictionary }) => {
    const out = {};
    const set = (target, keys, value) => {
      let node = target;
      keys.slice(0, -1).forEach((k) => (node = node[k] ??= {}));
      node[keys.at(-1)] = value;
    };
    for (const t of dictionary.allTokens) {
      if (t.path[0] === "creator") continue;
      const keys = t.path.map((p) => (/^\d/.test(p) ? p : camel(p)));
      const e = ext(t);
      if (t.path[0] === "semantic") {
        set(out, keys, {
          light: t.$value,
          dark: resolve(e.dark ?? t.$value, dictionary),
          ...(e.highContrast ? { highContrast: resolve(e.highContrast, dictionary) } : {}),
          ...(e.highContrastDark ? { highContrastDark: resolve(e.highContrastDark, dictionary) } : {}),
        });
      } else if (t.$type === "dimension" && /px$/.test(String(t.$value))) {
        set(out, keys, px(t.$value));
      } else if (t.$type === "duration") {
        set(out, keys, ms(t.$value));
      } else if (t.$type === "fontFamily") {
        set(out, keys, { stack: fontStack(t.$value, e.faces), families: t.$value });
      } else if (t.$type === "typography") {
        set(out, keys, { ...t.$value, fontSize: px(t.$value.fontSize) });
      } else {
        set(out, keys, t.$value);
      }
    }

    const pairings = {};
    for (const t of byPath(dictionary, ["creator", "pairing"])) {
      const e = ext(t);
      pairings[t.path[2]] = {
        id: t.path[2],
        label: e.label,
        display: { ...e.display, stack: fontStack(e.display.family, e.display.face) },
        body: { ...e.body, stack: fontStack(e.body.family, e.body.face) },
      };
    }
    const presets = {};
    for (const t of byPath(dictionary, ["creator", "preset"])) {
      presets[t.path[2]] = { id: t.path[2], ...ext(t) };
    }
    const templates = {};
    for (const t of byPath(dictionary, ["creator", "template"])) {
      templates[t.path[2]] = { id: t.path[2], ...ext(t) };
    }
    const shapes = {};
    for (const t of byPath(dictionary, ["creator", "button", "shape"])) shapes[t.path[3]] = px(t.$value);
    const cardShapes = {};
    for (const t of byPath(dictionary, ["creator", "card", "shape"])) cardShapes[t.path[3]] = px(t.$value);
    const buttonStyles = byPath(dictionary, ["creator", "button", "style"]).map((t) => t.$value);
    const swatches = {};
    for (const t of byPath(dictionary, ["creator", "swatch"])) swatches[t.path[2]] = t.original.$value;

    const json = (v) => JSON.stringify(v, null, 2);
    return `// ${HEADER}
/* eslint-disable */

export const tokens = ${json(out)} as const;

export const creatorTokens = {
  buttonHeight: ${px(resolve(dictionary.tokens.creator.button.height.$value, dictionary))},
  buttonShapes: ${json(shapes)},
  cardShapes: ${json(cardShapes)},
  buttonStyles: ${json(buttonStyles)},
  pairings: ${json(pairings)},
  presets: ${json(presets)},
  templates: ${json(templates)},
  swatches: ${json(swatches)},
} as const;

export type Tokens = typeof tokens;
export type SemanticColor = keyof typeof tokens.semantic;
export type CreatorButtonShape = keyof typeof creatorTokens.buttonShapes;
export type CreatorButtonStyle = (typeof creatorTokens.buttonStyles)[number];
export type CreatorPairingId = keyof typeof creatorTokens.pairings;
export type CreatorPresetId = keyof typeof creatorTokens.presets;
export type CreatorTemplateId = keyof typeof creatorTokens.templates;
`;
  },
});

