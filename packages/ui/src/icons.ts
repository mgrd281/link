/**
 * Media transport: play, pause, stop and skip mean the same in every language, so they never mirror,
 * and they are drawn solid (`solid`) so a play/pause toggle never mixes a filled and an outlined glyph.
 */
export const MEDIA_TRANSPORT: ReadonlySet<LucideIcon> = new Set<LucideIcon>([Play, Pause, Square, SkipForward, SkipBack, StepForward, StepBack, FastForward, Rewind]);

/** Whether a glyph mirrors in right-to-left text. */
export const isDirectional = (glyph: LucideIcon): boolean => DIRECTIONAL.has(glyph);
