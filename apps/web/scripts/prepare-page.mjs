#!/usr/bin/env node
/* eslint-disable no-console -- a command-line tool prints its result. */
/**
 * Turns a page built in the dashboard into a page prepared for a creator.
 *
 *   1. Build the page in the dashboard (any account) and use Settings → Export my data.
 *   2. node scripts/prepare-page.mjs --from export.json --email creator@example.com --name "Nizar"
 *      (several emails: --email a@x.com,b@y.com · optional --slug, --username)
 *   3. Commit, deploy, and send the creator the invite link this prints.
 *
 * Or publish a page the team built in the team area (/admin → creator → "Download file"):
 *
 *   node scripts/prepare-page.mjs --add linkyo-<slug>.json
 *
 * Publishing the same address again replaces the page and keeps the invites it already had.
 *
 * Uploaded pictures are written to public/prepared/<slug>/, emails are stored only as SHA-256.
 */
import { createHash, randomBytes } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { values } = parseArgs({
  options: {
    from: { type: "string" },
    email: { type: "string" },
    name: { type: "string" },
    slug: { type: "string" },
    username: { type: "string" },
    add: { type: "string" },
  },
});
const dataDir = join(root, "src", "features", "previews", "prepared");
const hash = (email) => createHash("sha256").update(email).digest("hex");

/** Pictures uploaded in the dashboard are data URLs: write them as files and link to them. */
function extractImages(slug, value) {
  const imageDir = join(root, "public", "prepared", slug);
  let count = 0;
  const walk = (inner) => {
    if (Array.isArray(inner)) return inner.map(walk);
    if (inner && typeof inner === "object") {
      return Object.fromEntries(
        Object.entries(inner).map(([key, item]) => {
          const match =
            key === "src" && typeof item === "string"
              ? /^data:image\/(jpeg|png|webp);base64,(.+)$/.exec(item)
              : null;
          if (!match) return [key, walk(item)];
          mkdirSync(imageDir, { recursive: true });
          const file = `${++count}.${match[1] === "jpeg" ? "jpg" : match[1]}`;
          writeFileSync(join(imageDir, file), Buffer.from(match[2], "base64"));
          return [key, `/prepared/${slug}/${file}`];
        }),
      );
    }
    return inner;
  };
  return { value: walk(value), count: () => count };
}

/** Regenerate the index the registry reads. */
function writeIndex() {
  const files = readdirSync(dataDir)
    .filter((file) => file.endsWith(".json"))
    .sort();
  writeFileSync(
    join(dataDir, "index.ts"),
    [
      "// Generated by scripts/prepare-page.mjs — do not edit by hand.",
      ...files.map((file, i) => `import p${i} from "./${file}";`),
      "",
      `export const PREPARED: unknown[] = [${files.map((_, i) => `p${i}`).join(", ")}];`,
      "",
    ].join("\n"),
  );
}

if (values.add) {
  const file = JSON.parse(readFileSync(values.add, "utf8"));
  const slug = String(file.slug ?? "");
  const pages = file.pages && typeof file.pages === "object" ? file.pages : null;
  if (!/^[a-z0-9-]{3,64}$/.test(slug) || !pages || !file.username || !Array.isArray(file.invite?.emailSha256)) {
    console.error("This file is not a page from the team area (/admin → creator → Download file).");
    process.exit(1);
  }
  mkdirSync(dataDir, { recursive: true });
  const target = join(dataDir, `${slug}.json`);
  // Invites already sent stay valid: the team area only knows their number, not the emails.
  const before = (() => {
    try {
      return JSON.parse(readFileSync(target, "utf8")).invite?.emailSha256 ?? [];
    } catch {
      return [];
    }
  })();
  const images = extractImages(slug, pages);
  const invites = [...new Set([...before, ...file.invite.emailSha256])].filter((item) => /^[0-9a-f]{64}$/.test(item));
  writeFileSync(
    target,
    `${JSON.stringify({ slug, name: file.name ?? {}, username: file.username, theme: file.theme ?? {}, pages: images.value, verified: file.verified === true, invite: { emailSha256: invites } }, null, 2)}\n`,
  );
  writeIndex();
  const locales = Object.keys(pages);
  console.log(`Published ${slug} (${locales.join(", ")}) with ${invites.length} invite(s), ${images.count()} picture(s).`);
  for (const locale of locales) {
    console.log(`Preview:     https://linkyo.app/${locale}/p/${slug}`);
    console.log(`Invite link: https://linkyo.app/${locale}/signup?name=${file.username}&invite=${slug}`);
  }
  process.exit(0);
}

if (!values.from || !values.email || !values.name) {
  console.error(
    'Usage: node scripts/prepare-page.mjs --from export.json --email creator@example.com --name "Name" [--slug x] [--username y]\n' +
      "   or: node scripts/prepare-page.mjs --add linkyo-<slug>.json",
  );
  process.exit(1);
}

const exported = JSON.parse(readFileSync(values.from, "utf8"));
const site = exported.site ?? exported;
if (!site?.page?.profile || !Array.isArray(site.page.blocks)) {
  console.error("This file is not a Linkyo export (Settings → Export my data).");
  process.exit(1);
}
const username = (values.username ?? site.page.profile.username).toLowerCase();
const slug = values.slug ?? `${username}-${randomBytes(4).toString("hex").slice(0, 6)}`;
const emails = values.email
  .split(",")
  .map((email) => email.trim().toLowerCase())
  .filter(Boolean);
const images = extractImages(slug, { profile: { ...site.page.profile, username }, blocks: site.page.blocks });
const page = images.value;
const count = images.count();
const locale = page.profile.locale ?? "de";

mkdirSync(dataDir, { recursive: true });
writeFileSync(
  join(dataDir, `${slug}.json`),
  `${JSON.stringify({ slug, name: { [locale]: values.name }, username, theme: site.theme ?? {}, pages: { [locale]: page }, invite: { emailSha256: emails.map(hash) } }, null, 2)}\n`,
);
writeIndex();

console.log(`Prepared ${slug} for ${emails.length} email(s), ${count} picture(s).`);
console.log(`Preview:     https://linkyo.app/${locale}/p/${slug}`);
console.log(`Invite link: https://linkyo.app/${locale}/signup?name=${username}&invite=${slug}`);
